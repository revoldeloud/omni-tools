const sourceByNode = new WeakMap<Text, string>();
const translatedByNode = new WeakMap<Text, string>();
const attributes = ["aria-label", "aria-description", "placeholder", "title", "alt"] as const;
const sourceByElement = new WeakMap<Element, Map<string, { source: string; output: string }>>();
let observer: MutationObserver | null = null;
let activeLanguage: UiLanguage = "pt-BR";

function translatePhrase(value: string, language: UiLanguage): string {
  if (language === "en") return value;
  if (translations[value]) return translations[value];
  return value.replace(/[A-Za-z]+(?:'[A-Za-z]+)?/g, (word) => {
    const exact = words[word];
    if (exact) return exact;
    const title = word[0].toUpperCase() + word.slice(1).toLowerCase();
    const titleMatch = words[title];
    if (!titleMatch) return word;
    return word === word.toUpperCase() ? titleMatch.toUpperCase() : word[0] === word[0].toUpperCase() ? titleMatch : titleMatch.toLowerCase();
  });
}

function translateText(node: Text) {
  const current = node.nodeValue ?? "";
  const knownOutput = translatedByNode.get(node);
  if (knownOutput !== undefined && current !== knownOutput) sourceByNode.set(node, current);
  const source = sourceByNode.get(node) ?? current;
  sourceByNode.set(node, source);
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const body = source.slice(leading.length, source.length - trailing.length || undefined);
  const output = `${leading}${translatePhrase(body, activeLanguage)}${trailing}`;
  translatedByNode.set(node, output);
  if (node.nodeValue !== output) node.nodeValue = output;
}

function translateElement(element: Element) {
  if (element.closest("[data-language-selector]")) return;
  let saved = sourceByElement.get(element);
  if (!saved) {
    saved = new Map();
    sourceByElement.set(element, saved);
  }
  for (const attribute of attributes) {
    const current = element.getAttribute(attribute);
    if (current === null) continue;
    const previous = saved.get(attribute);
    if (!previous || current !== previous.output) saved.set(attribute, { source: current, output: current });
    const source = saved.get(attribute)!.source;
    const output = translatePhrase(source, activeLanguage);
    saved.set(attribute, { source, output });
    if (current !== output) element.setAttribute(attribute, output);
  }
}

function translateTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || parent.closest("script, style, noscript, textarea, [data-language-selector]")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  let node: Node | null;
  while ((node = walker.nextNode())) translateText(node as Text);
  if (root instanceof Element) translateElement(root);
  root.querySelectorAll?.("*").forEach(translateElement);
}

export function getUiLanguage(): UiLanguage {
  if (typeof window === "undefined") return "pt-BR";
  const stored = window.localStorage.getItem("utitools-language");
  return stored === "en" ? "en" : "pt-BR";
}

export function setUiLanguage(language: UiLanguage) {
  activeLanguage = language;
  if (typeof window !== "undefined") {
    window.localStorage.setItem("utitools-language", language);
    document.documentElement.lang = language;
    window.dispatchEvent(new CustomEvent("utitools-language-change", { detail: language }));
    translateTree(document.body);
  }
}

export function startUiTranslation() {
  if (typeof document === "undefined") return () => undefined;
  activeLanguage = getUiLanguage();
  document.documentElement.lang = activeLanguage;
  translateTree(document.body);
  observer?.disconnect();
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData" && record.target instanceof Text) translateText(record.target);
      record.addedNodes.forEach((node) => {
        if (node instanceof Text) translateText(node);
        else if (node instanceof Element) translateTree(node);
      });
      if (record.type === "attributes" && record.target instanceof Element) translateElement(record.target);
    }
  });
  observer.observe(document.body, { childList: true, characterData: true, subtree: true, attributes: true, attributeFilter: [...attributes] });
  return () => observer?.disconnect();
}
